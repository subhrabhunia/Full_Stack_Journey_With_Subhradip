// JavaScript Do While Loop
let i = 1;

do {
    document.write(i + "<br>");
    i++;
}
while (i <= 10);

//Second Example of Do While Loop
var j=1;
do{
    document.write("Subhradip" + "<br>");
    j++;
}
while (j <= 10);

//Decrementing Do While Loop
var k=10;
do{
    document.write(k + "<br>");
    k--;
}
while (k >= 1);