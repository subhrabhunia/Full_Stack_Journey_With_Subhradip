

// Comparison Operators

let a = 10;
let b = 5;

// 1. Equal to (==)
console.log("Equal to (==):", a == b);

// 2. Strict Equal to (===)
console.log("Strict Equal to (===):", a === b);

// 3. Not Equal to (!=)
console.log("Not Equal to (!=):", a != b);

// 4. Strict Not Equal to (!==)
console.log("Strict Not Equal to (!==):", a !== b);

// 5. Greater than (>)
console.log("Greater than (>):", a > b);

// 6. Less than (<)
console.log("Less than (<):", a < b);

// 7. Greater than or Equal to (>=)
console.log("Greater than or Equal to (>=):", a >= b);

// 8. Less than or Equal to (<=)
console.log("Less than or Equal to (<=):", a <= b);

// 9. String and Number Comparison
let x = 10;
let y = "10";

console.log("Equal to (==):", x == y);
console.log("Strict Equal to (===):", x === y);


// ### **3. Important Comparison Operators**

// | Operator | Example   | Meaning                  |
// | -------- | --------- | ------------------------ |
// | `==`     | `a == b`  | Equal to                 |
// | `===`    | `a === b` | Strict equal to(Value and type equal)          |
// | `!=`     | `a != b`  | Not equal to             |
// | `!==`    | `a !== b` | Strict not equal to      |
// | `>`      | `a > b`   | Greater than             |
// | `<`      | `a < b`   | Less than                |
// | `>=`     | `a >= b`  | Greater than or equal to |
// | `<=`     | `a <= b`  | Less than or equal to    |