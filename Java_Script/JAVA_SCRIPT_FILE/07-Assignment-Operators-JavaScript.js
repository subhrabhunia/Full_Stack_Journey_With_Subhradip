
// Assignment Operator (=)
let a = 10;
document.write("Assignment (=): " + a + "<br>");

// Addition Assignment (+=)
a += 5;
document.write("Addition (+=): " + a + "<br>");

// Subtraction Assignment (-=)
a -= 3;
document.write("Subtraction (-=): " + a + "<br>");

// Multiplication Assignment (*=)
a *= 2;
document.write("Multiplication (*=): " + a + "<br>");

// Division Assignment (/=)
a /= 4;
document.write("Division (/=): " + a + "<br>");

// Modulus Assignment (%=)
a %= 3;
document.write("Modulus (%=): " + a + "<br>");

// Exponentiation Assignment (**=)
let b = 2;
b **= 3;
document.write("Exponentiation (**=): " + b + "<br>");
