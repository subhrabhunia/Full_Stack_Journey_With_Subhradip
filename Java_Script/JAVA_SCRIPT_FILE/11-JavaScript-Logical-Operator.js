
// Logical Operators

let a = 10;
let b = 5;
let c = 15;

// 1. Logical AND (&&)
document.write("Logical AND (&&): " + (a > b && a < c) + "<br>");

// 2. Logical OR (||)
document.write("Logical OR (||): " + (a > b || a > c) + "<br>");

// 3. Logical NOT (!)
document.write("Logical NOT (!): " + !(a > b) + "<br>");
