
// ARITHMETIC OPERATORS IN JAVASCRIPT:-


// Addition (+):-

var a = 10;
var b = 5;

var addition = a + b;

document.write("<h2>ADDITION</h2>");

document.write(a + " + " + b + " = " + addition + "<br>");


// Subtraction (-):-

var subtraction = a - b;

document.write("<h2>SUBTRACTION</h2>");

document.write(a + " - " + b + " = " + subtraction + "<br>");


// Multiplication (*):-

var multiplication = a * b;

document.write("<h2>MULTIPLICATION</h2>");

document.write(a + " * " + b + " = " + multiplication + "<br>");


// Exponentiation (**):-

var exponentiation = a ** b;

document.write("<h2>EXPONENTIATION</h2>");

document.write(a + " ** " + b + " = " + exponentiation + "<br>");


// Division (/):-

var division = a / b;

document.write("<h2>DIVISION</h2>");

document.write(a + " / " + b + " = " + division + "<br>");


// Modulus (%):-

var modulus = a % b;

document.write("<h2>MODULUS</h2>");

document.write(a + " % " + b + " = " + modulus + "<br>");


// Increment (++):-

var x = 10;

x++;

var increment = x;

document.write("<h2>INCREMENT</h2>");

document.write("10 + 1 = " + increment + "<br>");


// Decrement (--):-

var y = 10;

y--;

var decrement = y;

document.write("<h2>DECREMENT</h2>");

document.write("10 - 1 = " + decrement + "<br>");


// DISPLAY ARITHMETIC OPERATORS:-

document.write("<h2>ALL OPERATORS</h2>");

document.write("Addition: " + addition + "<br>");
document.write("Subtraction: " + subtraction + "<br>");
document.write("Multiplication: " + multiplication + "<br>");
document.write("Exponentiation: " + exponentiation + "<br>");
document.write("Division: " + division + "<br>");
document.write("Modulus: " + modulus + "<br>");
document.write("Increment: " + increment + "<br>");
document.write("Decrement: " + decrement + "<br>");
