
let i = 1;

while (i <= 10) {
    document.write("Subhradip" + "<br>");
    i++;
}

// Another Example of While Loop
var j = 1;
while (j <= 10) {
    document.write(j + "<br>");
    j++;
}

// Decrementing While Loop
var a=10;
while (a >= 1) {
    document.write(a + "<br>");
    a--;
}

//Loops in Html tag
var k = 1;
document.write("<ul>");
while (k <= 10) {
    document.write("<li>Subhradip</li>");
    k++;
}
document.write("</ul>");

